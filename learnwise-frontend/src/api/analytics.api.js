import { apiRequest } from './client';
export const analyticsApi = {
    studentOverview: (range = '30d') => apiRequest(`/analytics/student/overview/?range=${encodeURIComponent(range)}`),
    enrollments: () => apiRequest('/analytics/enrollments/'),
    enroll: (courseId) => apiRequest('/analytics/enrollments/enroll/', { method: 'POST', body: { course_id: courseId } }),
    learningPaths: () => apiRequest('/analytics/learning-paths/'),
    learningPath: (id) => apiRequest(`/analytics/learning-paths/${id}/`),
    learningSessions: (params = '') => apiRequest(`/analytics/learning-sessions/${params}`),
    startLearningSession: (courseId) => apiRequest('/analytics/learning-sessions/start/', { method: 'POST', body: { course_id: courseId } }),
    finishLearningSession: (id) => apiRequest(`/analytics/learning-sessions/${encodeURIComponent(id)}/finish/`, { method: 'PATCH' }),
    activities: (sessionId) => apiRequest(`/analytics/learning-activities/${sessionId ? `?session=${encodeURIComponent(sessionId)}` : ''}`),
    recordActivity: ({ session_id, ...rest }) => apiRequest('/analytics/learning-activities/record/', { method: 'POST', body: { ...rest, session: session_id } }),
    progress: (courseId) => apiRequest(`/analytics/progress/${courseId ? `?course=${encodeURIComponent(courseId)}` : ''}`),
    performance: (range = '30d') => apiRequest(`/analytics/performance/?range=${encodeURIComponent(range)}`),
    achievements: () => apiRequest('/analytics/achievements/'),
    dashboard: (range = '30d') => apiRequest(`/analytics/dashboard/?range=${encodeURIComponent(range)}`),
    recommendations: () => apiRequest('/analytics/recommendations/'),
    indicators: () => apiRequest('/analytics/student/indicators/'),
    weaknesses: (minimumAnswers = 2) => apiRequest(`/analytics/student/weaknesses/?minimum_answers=${minimumAnswers}`),
    cohortComparison: (cohortId) => apiRequest(`/analytics/cohorts/${encodeURIComponent(cohortId)}/comparison/`),
    radar: () => apiRequest('/analytics/radar/'),
    refreshRadar: () => apiRequest('/analytics/radar/', { method: 'POST' }),
    completeIntervention: (id) => apiRequest(`/analytics/interventions/${encodeURIComponent(id)}/complete/`, { method: 'POST' }),
    socketPath: () => '/ws/analytics/',
    teacherOverview: (range = '30d') => apiRequest(`/analytics/teacher/overview/?range=${encodeURIComponent(range)}`),
    adminOverview: (range = '30d') => apiRequest(`/analytics/admin/overview/?range=${encodeURIComponent(range)}`),
};
